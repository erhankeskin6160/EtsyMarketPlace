using System;
using System.Threading;
using System.Threading.Tasks;
using EtsyMarketPlace.Domain.Subscriptions;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;

namespace EtsyMarketPlace.Infrastructure.Database.Postgres;

/// <summary>
/// SaaS Abonelik Paketleri (subscription_plans, user_subscriptions, subscription_transactions) PostgreSQL
/// tablolarını ve app_users abonelik sütunlarını idempotent biçimde oluşturan / tohumlayan başlatıcı.
/// </summary>
public static class SubscriptionPostgresSchemaBootstrapper
{
    private static readonly SemaphoreSlim BootstrapLock = new(1, 1);

    public const string EnsureSchemaSql = """
        ALTER TABLE IF EXISTS app_users ADD COLUMN IF NOT EXISTS subscription_plan_id character varying(50) NOT NULL DEFAULT 'pro';
        ALTER TABLE IF EXISTS app_users ADD COLUMN IF NOT EXISTS subscription_status character varying(30) NOT NULL DEFAULT 'Active';
        ALTER TABLE IF EXISTS app_users ADD COLUMN IF NOT EXISTS subscription_expires_at timestamp with time zone NULL;

        CREATE TABLE IF NOT EXISTS subscription_plans (
            id character varying(50) NOT NULL,
            name character varying(100) NOT NULL,
            tagline character varying(500) NOT NULL DEFAULT '',
            badge_text character varying(64) NOT NULL DEFAULT '',
            accent_color character varying(32) NOT NULL DEFAULT '#38bdf8',
            monthly_price_usd numeric(18,2) NOT NULL DEFAULT 0,
            yearly_price_usd numeric(18,2) NOT NULL DEFAULT 0,
            monthly_price_try numeric(18,2) NOT NULL DEFAULT 0,
            yearly_price_try numeric(18,2) NOT NULL DEFAULT 0,
            max_shops integer NOT NULL DEFAULT 1,
            monthly_ai_token_quota integer NOT NULL DEFAULT 100000,
            max_monthly_ai_listings integer NOT NULL DEFAULT 15,
            max_batch_queue_size integer NOT NULL DEFAULT 0,
            allowed_features_json text NOT NULL DEFAULT '[]',
            is_popular boolean NOT NULL DEFAULT FALSE,
            is_active boolean NOT NULL DEFAULT TRUE,
            display_order integer NOT NULL DEFAULT 1,
            updated_at_utc timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
            CONSTRAINT "PK_subscription_plans" PRIMARY KEY (id)
        );

        CREATE TABLE IF NOT EXISTS user_subscriptions (
            id character varying(128) NOT NULL,
            user_id character varying(128) NOT NULL,
            plan_id character varying(50) NOT NULL,
            status character varying(30) NOT NULL DEFAULT 'Active',
            billing_cycle character varying(20) NOT NULL DEFAULT 'Monthly',
            start_date_utc timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
            current_period_start_utc timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
            current_period_end_utc timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
            auto_renew boolean NOT NULL DEFAULT TRUE,
            custom_max_shops_override integer NULL,
            custom_ai_token_quota_override integer NULL,
            payment_provider character varying(50) NOT NULL DEFAULT 'StripeVirtualPos',
            last_session_id character varying(128) NULL,
            updated_at_utc timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
            CONSTRAINT "PK_user_subscriptions" PRIMARY KEY (id)
        );

        CREATE UNIQUE INDEX IF NOT EXISTS "IX_user_subscriptions_user_id"
            ON user_subscriptions (user_id);

        CREATE TABLE IF NOT EXISTS subscription_transactions (
            id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
            session_id character varying(128) NOT NULL,
            user_id character varying(128) NOT NULL,
            username character varying(100) NOT NULL DEFAULT '',
            plan_id character varying(50) NOT NULL,
            plan_name character varying(100) NOT NULL DEFAULT '',
            billing_cycle character varying(20) NOT NULL DEFAULT 'Monthly',
            amount_usd numeric(18,2) NOT NULL DEFAULT 0,
            amount_try numeric(18,2) NOT NULL DEFAULT 0,
            currency character varying(10) NOT NULL DEFAULT 'USD',
            exchange_rate numeric(18,4) NOT NULL DEFAULT 35.0,
            status character varying(30) NOT NULL DEFAULT 'Pending',
            payment_provider character varying(50) NOT NULL DEFAULT 'StripeVirtualPos',
            card_masked_number character varying(32) NULL,
            card_holder_name character varying(150) NULL,
            invoice_number character varying(64) NOT NULL DEFAULT '',
            created_at_utc timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
            paid_at_utc timestamp with time zone NULL,
            CONSTRAINT "PK_subscription_transactions" PRIMARY KEY (id)
        );

        CREATE UNIQUE INDEX IF NOT EXISTS "IX_subscription_transactions_session_id"
            ON subscription_transactions (session_id);

        CREATE INDEX IF NOT EXISTS "IX_subscription_transactions_user_id_created"
            ON subscription_transactions (user_id, created_at_utc DESC);
        """;

    public static async Task<bool> EnsureTablesExistAsync(
        EtsyMarketPlaceDbContext context,
        ILogger? logger = null,
        CancellationToken cancellationToken = default)
    {
        if (context?.Database is null || !context.Database.IsRelational())
        {
            return false;
        }

        await BootstrapLock.WaitAsync(cancellationToken);
        try
        {
            await context.Database.ExecuteSqlRawAsync(EnsureSchemaSql, cancellationToken);

            var existingIds = await context.SubscriptionPlans
                .AsNoTracking()
                .Select(p => p.Id)
                .ToListAsync(cancellationToken);

            var existingSet = existingIds.ToHashSet(StringComparer.OrdinalIgnoreCase);
            var added = 0;
            foreach (var defaultPlan in SubscriptionFeatureKeys.GetDefaultPlans())
            {
                if (!existingSet.Contains(defaultPlan.Id))
                {
                    context.SubscriptionPlans.Add(defaultPlan);
                    added++;
                }
            }

            if (added > 0)
            {
                await context.SaveChangesAsync(cancellationToken);
                logger?.LogInformation("PostgreSQL: {Count} varsayılan abonelik paketi tohumlandı.", added);
            }

            return true;
        }
        catch (Exception ex) when (ex is not OperationCanceledException)
        {
            logger?.LogWarning(ex, "PostgreSQL abonelik tabloları oluşturulamadı veya tohumlanamadı: {Message}", ex.Message);
            return false;
        }
        finally
        {
            BootstrapLock.Release();
        }
    }
}
