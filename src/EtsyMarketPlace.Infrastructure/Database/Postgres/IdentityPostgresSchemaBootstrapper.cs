using System;
using System.Threading;
using System.Threading.Tasks;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;

namespace EtsyMarketPlace.Infrastructure.Database.Postgres;

/// <summary>
/// ASP.NET Core Identity PostgreSQL tablolarını (AspNetRoles, AspNetUsers, AspNetUserRoles vb.)
/// mevcut VDS veritabanlarında da sıfır hata ile idempotent biçimde güvence altına alan başlatıcı.
/// </summary>
public static class IdentityPostgresSchemaBootstrapper
{
    private static readonly SemaphoreSlim BootstrapLock = new(1, 1);

    public const string EnsureSchemaSql = """
        CREATE TABLE IF NOT EXISTS "AspNetRoles" (
            "Id" text NOT NULL,
            "Name" character varying(256) NULL,
            "NormalizedName" character varying(256) NULL,
            "ConcurrencyStamp" text NULL,
            CONSTRAINT "PK_AspNetRoles" PRIMARY KEY ("Id")
        );

        CREATE UNIQUE INDEX IF NOT EXISTS "RoleNameIndex"
            ON "AspNetRoles" ("NormalizedName");

        CREATE TABLE IF NOT EXISTS "AspNetUsers" (
            "Id" text NOT NULL,
            primary_role character varying(50) NOT NULL DEFAULT 'StoreOwner',
            assigned_shop_ids text NOT NULL DEFAULT '[]',
            monthly_ai_token_quota integer NOT NULL DEFAULT 500000,
            used_ai_tokens integer NOT NULL DEFAULT 0,
            is_active boolean NOT NULL DEFAULT TRUE,
            subscription_plan_id character varying(50) NOT NULL DEFAULT 'pro',
            subscription_status character varying(30) NOT NULL DEFAULT 'Active',
            subscription_expires_at timestamp with time zone NULL,
            created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
            last_login_at timestamp with time zone NULL,
            legacy_password_hash text NULL,
            legacy_password_salt text NULL,
            "UserName" character varying(256) NULL,
            "NormalizedUserName" character varying(256) NULL,
            "Email" character varying(256) NULL,
            "NormalizedEmail" character varying(256) NULL,
            "EmailConfirmed" boolean NOT NULL DEFAULT FALSE,
            "PasswordHash" text NULL,
            "SecurityStamp" text NULL,
            "ConcurrencyStamp" text NULL,
            "PhoneNumber" text NULL,
            "PhoneNumberConfirmed" boolean NOT NULL DEFAULT FALSE,
            "TwoFactorEnabled" boolean NOT NULL DEFAULT FALSE,
            "LockoutEnd" timestamp with time zone NULL,
            "LockoutEnabled" boolean NOT NULL DEFAULT TRUE,
            "AccessFailedCount" integer NOT NULL DEFAULT 0,
            CONSTRAINT "PK_AspNetUsers" PRIMARY KEY ("Id")
        );

        CREATE INDEX IF NOT EXISTS "EmailIndex"
            ON "AspNetUsers" ("NormalizedEmail");

        CREATE UNIQUE INDEX IF NOT EXISTS "UserNameIndex"
            ON "AspNetUsers" ("NormalizedUserName");

        CREATE TABLE IF NOT EXISTS "AspNetRoleClaims" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
            "RoleId" text NOT NULL,
            "ClaimType" text NULL,
            "ClaimValue" text NULL,
            CONSTRAINT "PK_AspNetRoleClaims" PRIMARY KEY ("Id"),
            CONSTRAINT "FK_AspNetRoleClaims_AspNetRoles_RoleId" FOREIGN KEY ("RoleId") REFERENCES "AspNetRoles" ("Id") ON DELETE CASCADE
        );

        CREATE INDEX IF NOT EXISTS "IX_AspNetRoleClaims_RoleId"
            ON "AspNetRoleClaims" ("RoleId");

        CREATE TABLE IF NOT EXISTS "AspNetUserClaims" (
            "Id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
            "UserId" text NOT NULL,
            "ClaimType" text NULL,
            "ClaimValue" text NULL,
            CONSTRAINT "PK_AspNetUserClaims" PRIMARY KEY ("Id"),
            CONSTRAINT "FK_AspNetUserClaims_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE
        );

        CREATE INDEX IF NOT EXISTS "IX_AspNetUserClaims_UserId"
            ON "AspNetUserClaims" ("UserId");

        CREATE TABLE IF NOT EXISTS "AspNetUserLogins" (
            "LoginProvider" text NOT NULL,
            "ProviderKey" text NOT NULL,
            "ProviderDisplayName" text NULL,
            "UserId" text NOT NULL,
            CONSTRAINT "PK_AspNetUserLogins" PRIMARY KEY ("LoginProvider", "ProviderKey"),
            CONSTRAINT "FK_AspNetUserLogins_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE
        );

        CREATE INDEX IF NOT EXISTS "IX_AspNetUserLogins_UserId"
            ON "AspNetUserLogins" ("UserId");

        CREATE TABLE IF NOT EXISTS "AspNetUserRoles" (
            "UserId" text NOT NULL,
            "RoleId" text NOT NULL,
            CONSTRAINT "PK_AspNetUserRoles" PRIMARY KEY ("UserId", "RoleId"),
            CONSTRAINT "FK_AspNetUserRoles_AspNetRoles_RoleId" FOREIGN KEY ("RoleId") REFERENCES "AspNetRoles" ("Id") ON DELETE CASCADE,
            CONSTRAINT "FK_AspNetUserRoles_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE
        );

        CREATE INDEX IF NOT EXISTS "IX_AspNetUserRoles_RoleId"
            ON "AspNetUserRoles" ("RoleId");

        CREATE TABLE IF NOT EXISTS "AspNetUserTokens" (
            "UserId" text NOT NULL,
            "LoginProvider" text NOT NULL,
            "Name" text NOT NULL,
            "Value" text NULL,
            CONSTRAINT "PK_AspNetUserTokens" PRIMARY KEY ("UserId", "LoginProvider", "Name"),
            CONSTRAINT "FK_AspNetUserTokens_AspNetUsers_UserId" FOREIGN KEY ("UserId") REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE
        );
        """;

    public static async Task EnsureTablesExistAsync(
        EtsyMarketPlaceDbContext db,
        ILogger? logger = null,
        CancellationToken cancellationToken = default)
    {
        await BootstrapLock.WaitAsync(cancellationToken);
        try
        {
            await db.Database.ExecuteSqlRawAsync(EnsureSchemaSql, cancellationToken);
            logger?.LogInformation("PostgreSQL ASP.NET Core Identity şeması doğrulandı.");
        }
        finally
        {
            BootstrapLock.Release();
        }
    }
}
